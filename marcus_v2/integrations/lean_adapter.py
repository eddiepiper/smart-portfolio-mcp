"""QuantConnect LEAN isolation adapter (backtest only).

What is used from LEAN: its daily-resolution fill semantics, re-implemented
deterministically in `execution_engine` (market orders at the next open; limit
buys fill when the low reaches the limit, at the better of open and limit;
stop-market sells fill when the low reaches the stop, at the worse of open and
stop when the bar gaps through it).

What is optional: a cross-check run of the same order through the real LEAN
engine in Docker. It is started with `--network none`, no brokerage config and
only the `backtest` entry point. In the build environment the `quantconnect/lean`
image could not be unpacked (disk allowance), so this path is NOT VERIFIED.

What is impossible by construction: live trading. `build_command` accepts only
the backtest verb, refuses anything matching a live-trading pattern, and the
deployed package ships no brokerage adapters or credentials.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from ..core.permissions import LiveTradingForbidden, assert_no_live_trading

ALLOWED_VERBS = {"backtest"}
IMAGE = "quantconnect/lean:latest"


class LeanUnavailable(Exception):
    pass


def build_command(verb: str, algorithm_dir: str | Path, extra: list[str] | None = None) -> list[str]:
    if verb not in ALLOWED_VERBS:
        raise LiveTradingForbidden(f"LEAN verb {verb!r} is not allowed; only {sorted(ALLOWED_VERBS)}")
    extra = extra or []
    cmd = ["docker", "run", "--rm", "--network", "none", "--read-only", "--tmpfs", "/tmp",
           "-v", f"{Path(algorithm_dir).resolve()}:/LeanCLI:ro", IMAGE,
           "--config", "/LeanCLI/config.json", *extra]
    assert_no_live_trading(cmd)
    return cmd


ALGORITHM_TEMPLATE = '''# Generated by marcus_v2 for an isolated LEAN backtest cross-check. Paper only.
from AlgorithmImports import *

class MarcusPaperOrderCheck(QCAlgorithm):
    def Initialize(self):
        self.SetStartDate({y0}, {m0}, {d0})
        self.SetEndDate({y1}, {m1}, {d1})
        self.SetCash({cash})
        self.sym = self.AddEquity("{ticker}", Resolution.Daily).Symbol
        self.done = False

    def OnData(self, data):
        if self.done or not data.ContainsKey(self.sym):
            return
        self.done = True
        {order_line}
'''


def render_algorithm(ticker: str, start, end, cash: float, side: str, qty: int, order_type: str, limit: float | None) -> str:
    q = qty if side == "buy" else -qty
    if order_type == "limit":
        line = f"self.LimitOrder(self.sym, {q}, {limit})"
    else:
        line = f"self.MarketOrder(self.sym, {q})"
    return ALGORITHM_TEMPLATE.format(y0=start.year, m0=start.month, d0=start.day, y1=end.year, m1=end.month,
                                     d1=end.day, cash=cash, ticker=ticker, order_line=line)


def engine_available() -> bool:
    if not shutil.which("docker"):
        return False
    try:
        out = subprocess.run(["docker", "image", "inspect", IMAGE], capture_output=True, timeout=20)
        return out.returncode == 0
    except Exception:  # noqa: BLE001
        return False


def run_backtest(algorithm_dir: str | Path, timeout_s: int = 900) -> subprocess.CompletedProcess:
    if not engine_available():
        raise LeanUnavailable(f"LEAN engine image {IMAGE} not available: cross-check NOT VERIFIED")
    return subprocess.run(build_command("backtest", algorithm_dir), capture_output=True, text=True, timeout=timeout_s)
